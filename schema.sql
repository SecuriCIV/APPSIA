-- Schéma Supabase pour l'application SIA (APPSIA)
-- Exécutez ce script dans le SQL Editor de Supabase pour créer la table documents

create table if not exists documents (
  id bigint generated by default as identity primary key,
  title text not null,
  tag text not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Activation de la sécurité au niveau des lignes (Row Level Security)
alter table documents enable row level security;

-- Politiques d'accès pour les utilisateurs et l'application
create policy "Lecture publique" on documents for select using (true);
create policy "Insertion publique" on documents for insert with check (true);
